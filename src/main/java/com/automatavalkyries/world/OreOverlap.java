package com.automatavalkyries.world;

import com.automatavalkyries.AutomataValkyries;
import net.minecraft.core.Holder;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.BlockTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.levelgen.feature.ConfiguredFeature;
import net.minecraft.world.level.levelgen.feature.configurations.OreConfiguration;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;
import org.slf4j.Logger;
import com.mojang.logging.LogUtils;

import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * 他 MOD の鉱石の生成との重なりを見つける（WorldgenConfig の skipWhenOtherModGenerates）。
 * <p>
 * 他 MOD の配置済みの地物が置くブロックが {@code forge:ores/<金属>} に入っていれば、その金属はその MOD が生成している。
 * 置くブロックはバニラの {@link OreConfiguration} のほか、独自の設定（Mekanism の大きさを変えられる鉱石など）も
 * フィールドの中の {@link OreConfiguration.TargetBlockState} / {@link BlockState}（とその一覧）を読んで見つける。
 * </p>
 */
public final class OreOverlap {

    private static final Logger LOGGER = LogUtils.getLogger();

    /** 地物の設定のクラス → ブロックが入っているかもしれないフィールド */
    private static final Map<Class<?>, List<Field>> FIELDS = new ConcurrentHashMap<>();
    /** 他 MOD の生成に譲った金属 → 譲った相手の地物（表示・テスト用） */
    private static final Map<String, String> SKIPPED = new ConcurrentHashMap<>();

    private OreOverlap() {}

    public static Map<String, String> skipped() {
        return Collections.unmodifiableMap(SKIPPED);
    }

    /**
     * features の中に、他 MOD の地物で metal の鉱石を置く物があれば、その地物の名前（無ければ null）
     */
    public static String findOther(Collection<Holder<PlacedFeature>> features, String metal) {
        TagKey<Block> ores = BlockTags.create(ResourceLocation.fromNamespaceAndPath("forge", "ores/" + metal));
        for (Holder<PlacedFeature> holder : features) {
            String name = holder.unwrapKey().map(k -> k.location().toString()).orElse("(inline)");
            if (name.startsWith(AutomataValkyries.MODID + ":")) continue;
            boolean places = holder.value().getFeatures().anyMatch(configured -> placesTag(configured, ores));
            if (places) return name;
        }
        return null;
    }

    static void noteSkipped(String metal, String other) {
        if (SKIPPED.put(metal, other) == null) {
            LOGGER.info("[worldgen] {} ore is generated by {}; not generating ours (skipWhenOtherModGenerates)", metal, other);
        }
    }

    private static boolean placesTag(ConfiguredFeature<?, ?> configured, TagKey<Block> ores) {
        for (BlockState state : placedStates(configured.config())) {
            if (state.is(ores)) return true;
        }
        return false;
    }

    /** 設定が置くブロック（OreConfiguration は直接、他はフィールドを 1 段だけ読む） */
    private static List<BlockState> placedStates(Object config) {
        List<BlockState> out = new ArrayList<>();
        if (config instanceof OreConfiguration ore) {
            for (OreConfiguration.TargetBlockState target : ore.targetStates) out.add(target.state);
            return out;
        }
        for (Field field : fields(config.getClass())) {
            try {
                collect(field.get(config), out);
            } catch (Throwable ignored) {
                // 読めないフィールドは飛ばす
            }
        }
        return out;
    }

    private static void collect(Object value, List<BlockState> out) {
        if (value instanceof BlockState state) out.add(state);
        else if (value instanceof OreConfiguration.TargetBlockState target) out.add(target.state);
        else if (value instanceof Collection<?> list) for (Object element : list) {
            if (element instanceof BlockState state) out.add(state);
            else if (element instanceof OreConfiguration.TargetBlockState target) out.add(target.state);
        }
    }

    private static List<Field> fields(Class<?> type) {
        return FIELDS.computeIfAbsent(type, t -> {
            List<Field> list = new ArrayList<>();
            for (Class<?> c = t; c != null && c != Object.class; c = c.getSuperclass()) {
                for (Field field : c.getDeclaredFields()) {
                    if (Modifier.isStatic(field.getModifiers())) continue;
                    Class<?> ft = field.getType();
                    if (BlockState.class.isAssignableFrom(ft) || OreConfiguration.TargetBlockState.class.isAssignableFrom(ft)
                            || Collection.class.isAssignableFrom(ft)) {
                        try {
                            field.setAccessible(true);
                            list.add(field);
                        } catch (Throwable ignored) {
                            // モジュールで閉じられたフィールドは使わない
                        }
                    }
                }
            }
            return list;
        });
    }
}
